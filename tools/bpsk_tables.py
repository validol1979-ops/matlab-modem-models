#!/usr/bin/env python3
"""Deterministic integer tables for the BPSK pilot; --check forbids drift."""
from pathlib import Path
import argparse
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'common/python'))
from bpsk_fixed import ATAN,RRC,COS,CUBIC
from psk_fixed import EQ_RECIPROCAL,EQ_STEP_TRAIN,EQ_STEP_DATA
from cpm_fixed import GAUSS,C0_TAPS


def files():
    folder=ROOT/'rtl/modems/bpsk_costas_2008_08_25'
    contents={folder/'tables/cos.mem':COS}
    for axis in range(4):contents[folder/f'tables/cubic{axis}.mem']=[row[axis] for row in CUBIC]
    result={p:''.join(f'{int(v)&0x3ffff:018b}\n' for v in values) for p,values in contents.items()}
    # Equalizer step*reciprocal, 24-bit unsigned: address {training, mantissa-512}.
    result[folder/'tables/eq_reciprocal.mem']=''.join(f'{step*int(v):024b}\n' for step in (EQ_STEP_DATA,EQ_STEP_TRAIN) for v in EQ_RECIPROCAL)
    lines=['// Generated by tools/bpsk_tables.py; integer constants, no real RTL.',
           'function automatic signed [17:0] rrc_coefficient(input integer index);',' case(index)']
    lines += [f"  {i}: rrc_coefficient=18'sd{v};" if v>=0 else f"  {i}: rrc_coefficient=-18'sd{-v};" for i,v in enumerate(RRC[:17])]
    lines += ["  default: rrc_coefficient=18'sd0;",' endcase','endfunction',
              'function automatic signed [31:0] atan_coefficient(input integer index);',' case(index)']
    lines += [f"  {i}: atan_coefficient=32'sd{v};" for i,v in enumerate(ATAN)]
    lines += ["  default: atan_coefficient=32'sd0;",' endcase','endfunction']
    # GMSK frequency taps, Q16, symmetric (index 0..16 of 33, centre 16).
    lines += ['function automatic signed [17:0] gauss_coefficient(input integer index);',' case(index)']
    lines += [f"  {i}: gauss_coefficient=18'sd{v};" for i,v in enumerate(GAUSS[:17])]
    lines += ["  default: gauss_coefficient=18'sd0;",' endcase','endfunction']
    # Coherent GMSK: Laurent C0 matched filter, 48 taps in Q15.
    lines += ['function automatic signed [17:0] c0_coefficient(input integer index);',' case(index)']
    lines += [f"  {i}: c0_coefficient=18'sd{v};" for i,v in enumerate(C0_TAPS)]
    lines += ["  default: c0_coefficient=18'sd0;",' endcase','endfunction']
    result[folder/'bpsk_constants.svh']='\n'.join(lines)+'\n'
    return result


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,expected in files().items():
        if args.check:
            if not path.is_file() or path.read_text()!=expected:raise RuntimeError(f'Stale table: {path}')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(expected)
    print('PASS BPSK tables')

if __name__=='__main__':main()
